const catalogs = { de, en };

export type MessageKey = keyof typeof de;

export function isLocale(v: unknown): v is Locale {
  return v === "de" || v === "en";
}

export function isUnits(v: unknown): v is Units {
  return v === "metric" || v === "imperial";
}

export function isTheme(v: unknown): v is Theme {
  return v === "dark" || v === "light";
}

export function isMapStyle(v: unknown): v is MapStyleId {
  return (
    v === "dark" ||
    v === "voyager" ||
    v === "positron" ||
    v === "osm" ||
    v === "satellite" ||
    v === "topo"
  );
}

export function t(locale: Locale, key: MessageKey, vars?: Record<string, string | number>) {
  let s: string = catalogs[locale][key] ?? de[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.replaceAll(`{${k}}`, String(v));
    }
  }
  return s;
}
